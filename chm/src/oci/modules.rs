//! Kernel modules, folded into the generated initramfs so a container-derived
//! guest can see its own devices.
//!
//! # Why this exists
//!
//! Cold boot attaches virtio devices on the MMIO transport. In every arm64
//! distro kernel measured, that transport is a *module*:
//!
//! ```text
//! CONFIG_VIRTIO_MMIO=m      <-- the bus itself
//! CONFIG_VIRTIO_NET=m
//! CONFIG_VIRTIO_BLK=m
//! ```
//!
//! and a container rootfs ships no `/lib/modules`. So the two halves can never
//! meet: the kernel needs modules, and the rootfs `chm image build` writes
//! cannot contain them. The guest boots perfectly and has no network and no
//! disk, under a host log saying the devices are attached. See issue #222.
//!
//! # Why the module's own `.modinfo` is the source of truth
//!
//! Every `.ko` is an ELF object carrying a `.modinfo` section with `name=`,
//! `depends=` and `vermagic=`. This module reads that section rather than the
//! `modules.dep` beside it, for two measured reasons:
//!
//! * **`modules.dep` is not always there.** It is generated by `depmod` when a
//!   package is *installed*, not shipped inside it. Measured:
//!   `linux-modules-6.8.0-71-generic_arm64.deb` contains 916-odd modules and no
//!   `modules.dep` at all.
//! * **`vermagic` is the string the kernel itself compares.** Checking it means
//!   a mismatch is refused on the same authority that would have refused it at
//!   `init_module` time, rather than on a filename we have chosen to trust.
//!
//! That last point is not hypothetical. Alpine's netboot `vmlinuz-virt` and its
//! `linux-virt` apk are both called "virt", both current, and are routinely
//! **different releases** — measured 6.6.134 against 6.6.142 on v3.20, and the
//! same skew on v3.21 and v3.22. Nothing in either name says so, and modules
//! from one silently will not load into the other.
//!
//! # Why the modules are not installed at `lib/modules/...`
//!
//! Because on a usr-merge image `/lib` is a **symlink** to `usr/lib`, and cpio
//! entries are unpacked in sorted order: `./lib/modules/x.ko` is reached before
//! `./usr/lib` exists, the symlink resolves to a directory that is not there
//! yet, and the kernel's unpacker drops the file **without a word**. This is
//! not a guess — it is the same trap [`super::nicfg::GUEST_PATH`] documents
//! having been bitten by, on `node:22-slim`, which is a usr-merge image.
//!
//! So modules land in [`GUEST_DIR`], a directory at the root that no base image
//! can have turned into a symlink, and are loaded by explicit path.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::fs;
use std::io::{self, Read};
use std::path::{Path, PathBuf};

use flate2::read::GzDecoder;
use zstd::stream::copy_decode;

/// Where the bundled modules are installed in the guest.
///
/// At the root and with a name of our own, for the reason in the module docs:
/// any directory the base image controls may be a symlink, and a symlink that
/// is not resolvable yet costs the file silently.
pub const GUEST_DIR: &str = "gimbal-modules";

