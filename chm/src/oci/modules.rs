    /// The reader must agree with the writer, and the only way to know is to
    /// use the real writer -- a hand-built fixture and a hand-written parser
    /// agree by construction, which is this repo's recorded #178/#180 failure.
    #[test]
    fn what_the_builder_ships_is_what_the_reader_finds() {
        let mut r = crate::oci::initramfs::Rootfs::default();
        r.insert(
            GUEST_DIR.to_string(),
            crate::oci::entry::EntryKind::Directory { mode: 0o755 },
            Vec::new(),
        );
        for n in ["virtio_mmio", "virtio_net"] {
            r.insert(
                format!("{GUEST_DIR}/{n}.ko"),
                crate::oci::entry::EntryKind::File {
                    mode: 0o644,
                    size: 3,
                },
                vec![1, 2, 3],
            );
        }
        // Ordinary image content, so the scan cannot just be matching ".ko".
        r.insert(
            "usr/lib/modules/other.ko".to_string(),
            crate::oci::entry::EntryKind::File {
                mode: 0o644,
                size: 1,
            },
            vec![0],
        );
        let cpio = crate::oci::initramfs::write_cpio(&r);

        let dir = std::env::temp_dir().join(format!("chm-bundlescan-{}", std::process::id()));
        fs::create_dir_all(&dir).unwrap();
        let p = dir.join("initramfs");
        fs::write(&p, &cpio).unwrap();
        let mut found = bundled_in_initramfs(&p);
        found.sort();
        fs::remove_dir_all(&dir).ok();

        assert_eq!(
            found,
            vec!["virtio_mmio".to_string(), "virtio_net".to_string()]
        );
    }

    /// An initramfs we cannot read must reinstate the warning, never withhold
    /// it: a line of unnecessary text costs nothing, a guest with no network
