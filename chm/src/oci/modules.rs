    fn fake_module(fields: &[&str]) -> Vec<u8> {
        let shstrtab = b"\0.modinfo\0.shstrtab\0";
        let mut modinfo = Vec::new();
        for f in fields {
            modinfo.extend_from_slice(f.as_bytes());
            modinfo.push(0);
        }

        let ehsize = 0x40_usize;
        let shentsize = 0x40_usize;
        let modinfo_off = ehsize;
        let shstrtab_off = modinfo_off + modinfo.len();
        let shoff = shstrtab_off + shstrtab.len();

        let mut out = vec![0_u8; shoff];
        out[..4].copy_from_slice(b"\x7fELF");
        out[4] = 2; // ELFCLASS64
        out[5] = 1; // ELFDATA2LSB
        out[0x28..0x30].copy_from_slice(&(shoff as u64).to_le_bytes());
        out[0x3a..0x3c].copy_from_slice(&(shentsize as u16).to_le_bytes());
        out[0x3c..0x3e].copy_from_slice(&3_u16.to_le_bytes()); // shnum
        out[0x3e..0x40].copy_from_slice(&2_u16.to_le_bytes()); // shstrndx
        out[modinfo_off..shstrtab_off].copy_from_slice(&modinfo);
        out[shstrtab_off..shoff].copy_from_slice(shstrtab);

        let mut section = |name: u32, off: usize, size: usize| {
            let mut sh = vec![0_u8; shentsize];
            sh[0..4].copy_from_slice(&name.to_le_bytes());
            sh[0x18..0x20].copy_from_slice(&(off as u64).to_le_bytes());
            sh[0x20..0x28].copy_from_slice(&(size as u64).to_le_bytes());
            out.extend_from_slice(&sh);
        };
        section(0, 0, 0); // SHN_UNDEF
        section(1, modinfo_off, modinfo.len()); // ".modinfo"
        section(10, shstrtab_off, shstrtab.len()); // ".shstrtab"
        out
    }

    fn tree_with(dir: &Path, modules: &[(&str, Vec<u8>)]) -> Tree {
        let kernel = dir.join("kernel/drivers");
        fs::create_dir_all(&kernel).unwrap();
        for (file, body) in modules {
            fs::write(kernel.join(file), body).unwrap();
        }
        Tree {
            root: dir.to_path_buf(),
            found: Found::Requested,
        }
    }

    fn tmp(name: &str) -> PathBuf {
        let p = std::env::temp_dir().join(format!("chm-mod-{}-{name}", std::process::id()));
        let _ = fs::remove_dir_all(&p);
        fs::create_dir_all(&p).unwrap();
        p
    }

    fn gz(data: &[u8]) -> Vec<u8> {
        let mut e = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::fast());
        e.write_all(data).unwrap();
        e.finish().unwrap()
    }

